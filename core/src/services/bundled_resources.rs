//! Read-only resources shipped with the app: `bundled-plugins/` and
//! `bundled-templates/`.
//!
//! Desktop and iOS read them from the bundle's resource directory. Android
//! keeps bundle resources inside the APK, where `resource_dir()` is the
//! `asset://localhost/` pseudo-path that `std::fs` cannot read, so `build.rs`
//! embeds the files for Android targets and [`prepare`] extracts them into the
//! app cache during setup.

use crate::error::AppError;
use std::path::PathBuf;

/// Directory containing `bundled-plugins/` and `bundled-templates/`.
pub fn root(app: &tauri::AppHandle) -> Result<PathBuf, AppError> {
    #[cfg(not(target_os = "android"))]
    {
        use tauri::Manager;
        app.path()
            .resource_dir()
            .map_err(|e| AppError::Custom(format!("resource_dir: {e}")))
    }
    #[cfg(target_os = "android")]
    {
        let _ = app;
        embedded::extracted_root()
    }
}

/// Make [`root`] readable. Android extracts the embedded copy when its
/// fingerprint differs from the last extraction; other platforms read the
/// bundle in place.
pub fn prepare() -> Result<(), AppError> {
    #[cfg(target_os = "android")]
    {
        embedded::extract()
    }
    #[cfg(not(target_os = "android"))]
    {
        Ok(())
    }
}

#[cfg(target_os = "android")]
mod embedded {
    use crate::error::AppError;
    use std::path::{Path, PathBuf};

    // Generated by build.rs: `FINGERPRINT: &str` and
    // `FILES: &[(&str, &[u8])]` (resource-relative path, contents).
    include!(concat!(env!("OUT_DIR"), "/bundled_resources.rs"));

    const STAMP: &str = ".fingerprint";

    pub(super) fn extracted_root() -> Result<PathBuf, AppError> {
        Ok(crate::services::portable::cache_root()?.join("bundled-resources"))
    }

    pub(super) fn extract() -> Result<(), AppError> {
        let root = extracted_root()?;
        if std::fs::read_to_string(root.join(STAMP)).is_ok_and(|stamp| stamp == FINGERPRINT) {
            return Ok(());
        }
        let parent = root
            .parent()
            .ok_or_else(|| AppError::Custom("bundled resources root has no parent".into()))?;
        // Stage beside the destination and swap it in, so readers never see a
        // half-written tree; a crash leaves no stamp and the next start redoes it.
        let staging = parent.join("bundled-resources.staging");
        remove_if_present(&staging)?;
        for (relative, bytes) in FILES {
            let path = staging.join(relative);
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(&path, bytes)?;
        }
        std::fs::write(staging.join(STAMP), FINGERPRINT)?;
        remove_if_present(&root)?;
        std::fs::rename(&staging, &root)?;
        Ok(())
    }

    fn remove_if_present(dir: &Path) -> Result<(), AppError> {
        match std::fs::remove_dir_all(dir) {
            Ok(()) => Ok(()),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(error) => Err(error.into()),
        }
    }
}
